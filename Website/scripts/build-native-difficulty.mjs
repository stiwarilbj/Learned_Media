import { readFileSync, writeFileSync } from "node:fs";
import ts from "typescript";
const policy = JSON.parse(readFileSync(new URL("../lib/difficulty-policy.json", import.meta.url), "utf8"));
const quote = JSON.stringify;
const swift = `// Generated by Website/scripts/build-native-difficulty.mjs; edit difficulty-policy.json.
import Foundation

public enum DifficultyPolicy {
    public static let version = ${quote(policy.version)}
    public static let innerSectionFrom = ${policy.innerSectionFrom}
    public static let levels = [${policy.levels.map(quote).join(", ")}]
    public static func rubric(_ level: Int) -> String {
        let target = max(1, min(10, level))
        let evidence = target >= innerSectionFrom ? ${quote(policy.innerEvidence)} : ${quote(policy.easyEvidence)}
        return "Difficulty \\(target)/10: " + levels[target - 1] + " " + ${quote(policy.common)} + " " + evidence
    }
}
`;
const compiled = ts.transpileModule(readFileSync(new URL("../lib/recommendations.ts", import.meta.url), "utf8"), {
  compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022, esModuleInterop: true }
}).outputText;
const runtime = `// Generated by Website/scripts/build-native-difficulty.mjs.\n(function(scope) { const exports = {}; const require = () => (${JSON.stringify(policy)});\n${compiled}\nscope.LEARNED_MEDIA_DIFFICULTY = exports; })(globalThis);\n`;
for (const [path, value] of [["../../App/Sources/LearnedMediaCore/DifficultyPolicy.swift", swift], ["../../App/Resources/frontend/difficulty.js", runtime]]) {
  const target = new URL(path, import.meta.url);
  if (process.argv.includes("--check")) {
    if (readFileSync(target, "utf8") !== value) throw new Error("Native difficulty policy is stale; run npm run generate:native.");
  } else writeFileSync(target, value);
}
