import { readFileSync } from "node:fs";
import { writeFileSync } from "./generated-output.mjs";
import ts from "typescript";

const source = readFileSync(new URL("../lib/card-explanations.ts", import.meta.url), "utf8");
const compiled = ts.transpileModule(source, {
  compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 }
}).outputText;
const generated = "// Generated by Website/scripts/build-native-card-explanations.mjs.\n(function(scope) { const exports = {}; const require = () => scope.LEARNED_MEDIA_CARD_CONTENT_FINGERPRINT;\n" + compiled + "\nscope.LEARNED_MEDIA_CARD_EXPLANATIONS = exports; })(globalThis);\n";
const target = new URL("../../App/Resources/frontend/card-explanations.js", import.meta.url);
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== generated) throw new Error("Native card explanation helpers are stale; run npm run generate:native.");
} else writeFileSync(target, generated);
