import { readFileSync, writeFileSync } from "node:fs";
const rules = JSON.parse(readFileSync(new URL("../lib/prompt-instructions.json", import.meta.url), "utf8"));
const quote = value => JSON.stringify(value);
const entries = Object.entries(rules).map(([key, values]) => `        ${quote(key)}: [${values.map(quote).join(", ")}]`).join(",\n");
const generated = `// Generated by Website/scripts/build-native-prompts.mjs; edit prompt-instructions.json.\nimport Foundation\n\npublic enum PromptInstructions {\n    public static let rules: [String: [String]] = [\n${entries}\n    ]\n}\n`;
const target = new URL("../../App/Sources/LearnedMediaCore/PromptInstructions.swift", import.meta.url);
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== generated) throw new Error("Native prompt instructions are stale; run npm run generate:prompts.");
} else writeFileSync(target, generated);
