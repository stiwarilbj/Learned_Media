import {readFileSync, writeFileSync} from 'node:fs';
import ts from 'typescript';
const source=readFileSync(new URL('../lib/account-credentials.ts',import.meta.url),'utf8');
const code=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2020,module:ts.ModuleKind.CommonJS}}).outputText;
const output='// Generated by Website/scripts/build-native-credentials.mjs.\n(function(exports) {\n'+code+'\nwindow.LearnedMediaCredentials = exports;\n})({});\n';
const target=new URL('../../App/Resources/frontend/account-credentials.js',import.meta.url);
if(process.argv.includes('--check')) {
  if(readFileSync(target,'utf8')!==output) throw new Error('Native credentials runtime is stale.');
} else writeFileSync(target,output);
