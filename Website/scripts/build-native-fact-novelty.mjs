import { readFileSync, writeFileSync } from "node:fs";
import ts from "typescript";

const compiled = ts.transpileModule(readFileSync(new URL("../lib/fact-novelty.ts", import.meta.url), "utf8"), {
  compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 }
}).outputText;
const generated = "// Generated by Website/scripts/build-native-fact-novelty.mjs.\n(function(scope) { const exports = {};\n" + compiled + "\nscope.LEARNED_MEDIA_FACT_NOVELTY = exports; })(globalThis);\n";
const target = new URL("../../App/Resources/frontend/fact-novelty.js", import.meta.url);
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== generated) throw new Error("Native fact novelty helpers are stale; run npm run generate:native.");
} else writeFileSync(target, generated);
