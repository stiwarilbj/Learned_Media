import { readFileSync } from 'node:fs';
import { writeFileSync } from "./generated-output.mjs";
import ts from 'typescript';

const compiled = ts.transpileModule(readFileSync(new URL('../lib/card-follow-ups.ts', import.meta.url), 'utf8'), {
  compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 }
}).outputText;
const generated = '// Generated by Website/scripts/build-native-follow-ups.mjs.\n(function(scope) { const exports = {}; const require = () => scope.LEARNED_MEDIA_CARD_CONTENT_FINGERPRINT;\n' + compiled + '\nscope.LEARNED_MEDIA_CARD_FOLLOW_UPS = exports; })(globalThis);\n';
const target = new URL('../../App/Resources/frontend/card-follow-ups.js', import.meta.url);
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== generated) throw new Error('Native card follow-up helper is stale; run npm run generate:native.');
} else writeFileSync(target, generated);
