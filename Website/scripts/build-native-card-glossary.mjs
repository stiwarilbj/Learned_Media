import { readFileSync } from "node:fs";
import { writeFileSync } from "./generated-output.mjs";
import ts from "typescript";

const compiled = ts.transpileModule(readFileSync(new URL("../lib/card-glossary.ts", import.meta.url), "utf8"), {
  compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 }
}).outputText;
const generated = "// Generated by Website/scripts/build-native-card-glossary.mjs.\n(function(scope) { const exports = {}; const require = () => scope.LEARNED_MEDIA_CARD_EXPLANATIONS;\n" + compiled + "\nscope.LEARNED_MEDIA_CARD_GLOSSARY = exports; })(globalThis);\n";
const target = new URL("../../App/Resources/frontend/card-glossary.js", import.meta.url);
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== generated) throw new Error("Native card glossary helpers are stale; run npm run generate:native.");
} else writeFileSync(target, generated);
