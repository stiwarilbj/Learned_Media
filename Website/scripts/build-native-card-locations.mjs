import { readFileSync,  copyFileSync, mkdirSync } from "node:fs";
import { writeFileSync } from "./generated-output.mjs";
import ts from "typescript";

const source = new URL("../lib/card-locations.ts", import.meta.url);
const compiled = ts.transpileModule(readFileSync(source, "utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const runtime = "// Generated by Website/scripts/build-native-card-locations.mjs.\n(function(scope) { const exports = {}; const require = (id) => id === \"./card-tool-state-retention\" ? scope.LEARNED_MEDIA_CARD_TOOL_RETENTION : id === \"./card-content-fingerprint\" ? scope.LEARNED_MEDIA_CARD_CONTENT_FINGERPRINT : scope.LEARNED_MEDIA_CARD_REVEAL;\n" + compiled + "\nscope.LEARNED_MEDIA_CARD_LOCATIONS = exports; })(globalThis);\n";
const runtimeTarget = new URL("../../App/Resources/frontend/card-locations.js", import.meta.url);
const dataSource = new URL("../public/country-outlines.json", import.meta.url);
const dataTarget = new URL("../../App/Resources/frontend/country-outlines.json", import.meta.url);
mkdirSync(new URL("../../App/Resources/frontend/", import.meta.url), { recursive: true });
if (process.argv.includes("--check")) {
  if (readFileSync(runtimeTarget, "utf8") !== runtime) throw new Error("Native card location helpers are stale; run npm run generate:native.");
  if (!readFileSync(dataTarget).equals(readFileSync(dataSource))) throw new Error("Native country outline data is stale; run npm run generate:native.");
} else {
  writeFileSync(runtimeTarget, runtime);
  copyFileSync(dataSource, dataTarget);
}
