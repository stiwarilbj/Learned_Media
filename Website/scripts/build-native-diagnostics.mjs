import { readFileSync } from 'node:fs';
import { writeFileSync } from "./generated-output.mjs";
import { runInNewContext } from 'node:vm';
import ts from 'typescript';
const compile = path => ts.transpileModule(readFileSync(new URL(path, import.meta.url), 'utf8'), {
  compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 }
}).outputText;
const schemaCode = compile('../lib/provider-schema-diagnostics.ts');
// Evaluate only the pure diagnostics module; no provider responses or services are involved.
const schemaExports = {};
runInNewContext(schemaCode, { exports: schemaExports });
const definitions = Object.entries(schemaExports.providerSchemaFields);
const cases = new Set();
const caseName = id => id.replace(/\.([a-z])/, (_, letter) => letter.toUpperCase());
for (const [id, fields] of definitions) {
  if (!/^[a-z]+\.[a-z][a-zA-Z0-9]*$/.test(id)) throw new Error(`Invalid provider schema ID: ${id}`);
  const swiftCase = caseName(id);
  if (cases.has(swiftCase)) throw new Error(`Duplicate Swift schema case: ${swiftCase}`);
  cases.add(swiftCase);
  if (!Array.isArray(fields) || fields[0] !== '$' || fields.length !== new Set(fields).size
    || fields.some(field => typeof field !== 'string' || field !== '$' && !/^[a-zA-Z][a-zA-Z0-9_]*(?:\[0\])?(?:\.[a-zA-Z][a-zA-Z0-9_]*(?:\[0\])?)*$/.test(field))) {
    throw new Error(`Invalid provider schema paths: ${id}`);
  }
}
if (!definitions.length) throw new Error('No provider schema definitions found.');
writeFileSync(new URL('../../App/Sources/LearnedMediaCore/ProviderResponseSchema.generated.swift', import.meta.url),
  '// Generated by Website/scripts/build-native-diagnostics.mjs. Do not edit.\n'
  + '// Source: Website/lib/provider-schema-diagnostics.ts (schema IDs and ordered field paths).\n'
  + 'public enum ProviderResponseSchema: String, CaseIterable {\n'
  + definitions.map(([id]) => `    case ${caseName(id)} = ${JSON.stringify(id)}`).join('\n')
  + '\n\n    var fields: [String] {\n        switch self {\n'
  + definitions.map(([id, fields]) => `        case .${caseName(id)}: return [${fields.map(field => JSON.stringify(field)).join(', ')}]`).join('\n')
  + '\n        }\n    }\n}\n');
const code = compile('../lib/performance-diagnostics.ts');
writeFileSync(new URL('../../App/Resources/frontend/performance-diagnostics.js', import.meta.url),
  '// Generated by Website/scripts/build-native-diagnostics.mjs.\n(function(scope) { const schema = (() => { const exports = {};\n' + schemaCode + '\nreturn exports; })();\nconst require = () => schema; const exports = {};\n' + code + '\nscope.LEARNED_MEDIA_DIAGNOSTICS = exports; })(globalThis);\n');
