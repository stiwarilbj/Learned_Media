import { readFileSync } from 'node:fs';
import { writeFileSync } from "./generated-output.mjs";
import ts from 'typescript';

const compiled = ts.transpileModule(readFileSync(new URL('../lib/batch-replay.ts', import.meta.url), 'utf8'), {
  compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 }
}).outputText;
const generated = '// Generated by Website/scripts/build-native-batch-replay.mjs.\n(function(scope) { const exports = {};\n' + compiled + '\nscope.LEARNED_MEDIA_BATCH_REPLAY = exports; })(globalThis);\n';
const target = new URL('../../App/Resources/frontend/batch-replay.js', import.meta.url);
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== generated) throw new Error('Native batch replay helper is stale; run npm run generate:native.');
} else writeFileSync(target, generated);
