import { readFileSync } from "node:fs";
import { writeFileSync } from "./generated-output.mjs";
import ts from "typescript";

const compiled = ts.transpileModule(readFileSync(new URL("../lib/card-tool-state-retention.ts", import.meta.url), "utf8"), {
  compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 }
}).outputText;
const generated = "// Generated by Website/scripts/build-native-card-tool-state-retention.mjs.\n(function(scope) { const exports = {};\n" + compiled + "\nscope.LEARNED_MEDIA_CARD_TOOL_RETENTION = exports; })(globalThis);\n";
const target = new URL("../../App/Resources/frontend/card-tool-state-retention.js", import.meta.url);
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== generated) throw new Error("Native card tool retention helper is stale; run npm run generate:native.");
} else writeFileSync(target, generated);
