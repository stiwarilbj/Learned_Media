import { readFileSync } from "node:fs";
import { writeFileSync } from "./generated-output.mjs";
import ts from "typescript";

const compiled = ts.transpileModule(readFileSync(new URL("../lib/answer-structure.ts", import.meta.url), "utf8"), {
  compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 }
}).outputText;
const generated = "// Generated by Website/scripts/build-native-answer-structure.mjs.\n(function(scope) { const exports = {};\n" + compiled + "\nscope.LEARNED_MEDIA_ANSWER_STRUCTURE = exports; })(globalThis);\n";
const target = new URL("../../App/Resources/frontend/answer-structure.js", import.meta.url);
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== generated) throw new Error("Native answer structure helpers are stale; run npm run generate:native.");
} else writeFileSync(target, generated);
